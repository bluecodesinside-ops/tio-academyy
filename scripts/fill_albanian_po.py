def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def flatten_msgid(raw: str) -> str:
    parts = re.findall(r'"(.*?)"', raw, flags=re.S)
    msgid = "".join(parts)
    return msgid.replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")


def main() -> None:
    text = PO.read_text(encoding="utf-8")
    chunks = re.split(r"(?=\nmsgid )", text)
    header = chunks[0]
    entries = chunks[1:]

    out = [header.rstrip()]
    updated = 0
    seen = set()

    for entry in entries:
        entry = entry.strip("\n")
        # Drop fuzzy / previous-msgid markers when we override
        cleaned = re.sub(r"^#, fuzzy.*\n", "", entry, flags=re.M)
        cleaned = re.sub(r"^#\|.*\n", "", cleaned, flags=re.M)

        m = re.search(
            r"msgid ((?:\".*\"(?:\n|$))+)\s*msgstr ((?:\".*\"(?:\n|$))+)",
            cleaned,
            flags=re.M,
        )
        if not m:
            out.append(entry)
            continue

        msgid = flatten_msgid(m.group(1))
        seen.add(msgid)
        comments = cleaned[: m.start()].rstrip()

        if msgid in TR:
            sq = TR[msgid]
        else:
            sq = TR.get(msgid.replace("%%", "%"))
        if sq:
            body = f'msgid "{esc(msgid)}"\nmsgstr "{esc(sq)}"'
            rebuilt = f"{comments}\n{body}".strip() if comments else body
            out.append(rebuilt)
            updated += 1
        else:
            out.append(cleaned if cleaned != entry else entry)

    for en, sq in TR.items():
        if en not in seen:
            out.append(f'msgid "{esc(en)}"\nmsgstr "{esc(sq)}"')
            updated += 1

    PO.write_text("\n\n".join(out).strip() + "\n", encoding="utf-8")
    print(f"wrote {updated} overrides; catalog keys={len(seen)}")

    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "settings")
    try:
        django.setup()
        call_command("compilemessages", locale=["sq"], verbosity=0)
        translation.activate("sq")
        for s in [
            "Home",
            "About",
            "Learn from home. Train with purpose.",
            "Who we are",
            "Browse Courses",
            "Course Access",
            "Unlock for",
        ]:
            print(f"{s!r} => {_(s)!r}")
    except Exception as exc:
        print(f"compilemessages skipped: {exc}")


if __name__ == "__main__":
    main()
